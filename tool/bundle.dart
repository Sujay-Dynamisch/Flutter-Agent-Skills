// Regenerates lib/src/bundle.g.dart from skills/ and templates/.
// Run: dart run tool/bundle.dart
import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

String generateBundle(String packageRoot) {
  final files = <String, String>{};
  for (final dir in ['skills', 'templates']) {
    final root = Directory(p.join(packageRoot, dir));
    for (final f in root.listSync(recursive: true).whereType<File>()) {
      final rel =
          p.posix.joinAll(p.split(p.relative(f.path, from: packageRoot)));
      files[rel] = f.readAsStringSync().replaceAll('\r\n', '\n');
    }
  }
  final keys = files.keys.toList()..sort();
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/bundle.dart - do not edit by hand.')
    ..writeln()
    ..writeln('const bundledFiles = <String, String>{');
  for (final k in keys) {
    String lit(String s) => jsonEncode(s).replaceAll(r'$', r'\$');
    b.writeln('  ${lit(k)}: ${lit(files[k]!)},');
  }
  b.writeln('};');
  return b.toString();
}

void main() {
  final root = p.dirname(p.dirname(p.fromUri(Platform.script)));
  File(p.join(root, 'lib', 'src', 'bundle.g.dart'))
      .writeAsStringSync(generateBundle(root));
  stdout.writeln('Wrote lib/src/bundle.g.dart');
}
